## AIRFOIL CONSTRUCTION
# --------------------------------------------------------------------------
# Airfoil composite type
# Fields
# - name: airfoil name
# - database: airfoil database
# - state: airfoil state
#
@with_kw struct Airfoil

    name::String
    database::AirfoilDatabase
    state::AirfoilState = AirfoilState()

end


"""
    create_Airfoil(; kwargs...)

Airfoil constructor

# Keyword Arguments
- `name::Union{Missing,String}`: name of the airfoil
- `database::Union{Missing,AirfoilDatabase}`: airfoil database
- `Ma::Real`: Mach number
"""
function create_Airfoil(; 
    name::Union{Missing,String}=missing,
    database::Union{Missing,AirfoilDatabase}=missing,
    Ma::Real=0.0
    )

    # Validate
    @assert ismissing(name) != ismissing(database) "One and only one of name or database must be provided"
    @assert ismissing(name) || haskey(AIRFOIL_DATABASES,name) "Airfoil name $name not found in database, available names: $(keys(AIRFOIL_DATABASES))"

    # Airfoil name
    name = ismissing(name) ? database.name : name

    # Database
    db = ismissing(database) ? AIRFOIL_DATABASES[name] : database

    # Initialize airfoil
    airfoil = Airfoil(name=name,database=db)

    # Update parameters with input flow conditions
    update_all_airfoil_parameters!(airfoil,Ma)

    return airfoil

end
export create_Airfoil


## UPDATE FUNCTIONS
# ----------------------------------------------------------------------------
# Bracket weight function for interpolation
@inline function bracket_weight(MaRng, Ma)

    # Find the index of the largest Mach number less than or equal to Ma
    i = searchsortedlast(MaRng,Ma)
    i = clamp(i,1,length(MaRng)-1)

    # Get the two bracketing Mach numbers
    Ma1 = MaRng[i]
    Ma2 = MaRng[i+1]

    # Compute weight for linear interpolation
    w = (Ma-Ma1)/(Ma2-Ma1)

    return i,w

end

# Update function for all parameters in a database
@inline lerp(v,i,w) = muladd(w,v[i+1]-v[i],v[i])
@generated function update_state!(state::S,data::NamedTuple{names},i,w) where {S,names}
    Expr(:block,
        [:(state.$n = lerp(data.$n,i,w)) for n in names]...
    )
end

# Generic update function for parameters in a database
function update_parameters!(state, db, Ma)

    # Set Mach number within bounds of database
    Ma = clamp(Ma, db.MaRng[1], db.MaRng[end])

    # Find bracketing index and weight
    i, w = bracket_weight(db.MaRng, Ma)

    # Update attached flow parameters interpolating the database
    update_state!(state, db.data, i, w)

    # Fix cnα with Prandtl-Glauert compressibility factor
    state.cnα /= sqrt(1 - Ma^2)

end

# Update attached flow parameters
update_attached_flow_parameters!(airfoil, Ma) = update_parameters!(airfoil.state.attached, airfoil.database.attached, Ma)

# Update BLi parameters
update_BLi_parameters!(airfoil, Ma) = update_parameters!(airfoil.state.bli, airfoil.database.bli, Ma)

# Update BLo parameters
update_BLo_parameters!(airfoil, Ma) = update_parameters!(airfoil.state.blo, airfoil.database.blo, Ma)


"""
    update_all_airfoil_parameters!(airfoil,Ma)

Update all airfoil parameters based on the current Mach number.

# Arguments
- `airfoil::Airfoil`: airfoil object to update
- `Ma::Real`: Mach number
"""
function update_all_airfoil_parameters!(airfoil::Airfoil,Ma::Real)
    update_attached_flow_parameters!(airfoil,Ma)
    update_BLi_parameters!(airfoil,Ma)
    update_BLo_parameters!(airfoil,Ma)
end
export update_all_airfoil_parameters!


## MODIFIED DATABASE CONSTRUCTION
# -----------------------------------------------------------------------------
"""
    modified_database(name; attached,bli,blo,flap)

Creates a new airfoil database by modifying selected parameters of an existing
one.

Scalar values are automatically expanded to all Mach numbers.

# Arguments
- `name::String`: name of the airfoil whose database will be modified

# Keyword Arguments
- `attached::NamedTuple`: named tuple of attached flow parameters to modify
- `bli::NamedTuple`: named tuple of BLi parameters to modify
- `blo::NamedTuple`: named tuple of BLo parameters to modify
- `flap::NamedTuple`: named tuple of flap parameters to modify

# Example
--------
db = modified_database(
    "FlatPlate";
    attached = (
        cd₀ = 0.015,
        cnα = 6.1,
    ),
    bli = (
        α₀N = deg2rad(2.0),
    ),
    flap = (
        75 => create_FlapParameters(0.30,-0.22,1.05),
    )
)
"""
function modified_database(name; 
    attached=NamedTuple(),
    bli=NamedTuple(),
    blo=NamedTuple(),
    flap=NamedTuple()
    )

    # Set the old database
    old = AIRFOIL_DATABASES[name]

    # Crete a new database with modified parameters 
    return AirfoilDatabase(
        "$(old.name)_MOD",
        old.coordinates,
        _modify_database(old.attached, attached),
        _modify_database(old.bli, bli),
        _modify_database(old.blo, blo),
        _modify_database(old.flap, flap),
        old.circulation,
    )

end
export modified_database

# Modifier for aerodynamic models databases
function _modify_database(db, changes)

    # Quick return if no changes
    isempty(changes) && return db

    # Mach number vector length
    N = length(db.MaRng)

    # Work on a local copy because database structs are immutable
    newData = db.data

    # Loop over changes and update the database
    for (key,val) in pairs(changes)
        values = val isa Number ?
                 SVector{N}(fill(val,N)) :
                 SVector{N}(val)
        newData = merge(newData, (; key => values))
    end

    # Return a new database with the modified data
    return typeof(db)(db.MaRng,newData)

end

# Modifier for flap database
function _modify_database(db::FlapDatabase, changes::Tuple{Vararg{<:Pair}})

    # Quick return if no changes
    isempty(changes) && return db

    # Return a new database with the modified data
    return typeof(db)(merge(db.parameters,Dict(changes)))

end


