## PARAMETER STRUCTURES
# --------------------------------------------------------------------------
# Circulation parameters composite type
# Fields
# - `γbC2`: correction factor for 2-state indicial function
# - `γbC3`: correction factor for 3-state indicial function
#
struct CirculationParameters

    γbC2::SVector{2,Float64}
    γbC3::SVector{3,Float64}

end


# Flap parameters composite type
# Fields
# - `cdδ`: change in drag coefficient due to unit flap deflection
# - `cmδ`: change in moment coefficient due to unit flap deflection
# - `cnδ`: change in normal force coefficient due to unit flap deflection
#
struct FlapParameters

    cdδ::Float64
    cmδ::Float64
    cnδ::Float64

end


"""
    create_FlapParameters(cdδ, cmδ, cnδ)

Creates a flap parameter set for a TableLookup FlapAeroSolver

# Arguments
- `cdδ::Real`: change in drag coefficient due to unit flap deflection
- `cmδ::Real`: change in moment coefficient due to unit flap deflection
- `cnδ::Real`: change in normal force coefficient due to unit flap deflection

"""
function create_FlapParameters(cdδ::Real, cmδ::Real, cnδ::Real)
    return FlapParameters(Float64(cdδ), Float64(cmδ), Float64(cnδ))
end
export create_FlapParameters


